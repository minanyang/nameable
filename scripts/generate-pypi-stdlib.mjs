// Regenerates packages/core/src/data/pypi-stdlib.ts, the names PyPI refuses because they collide with the
// Python standard library. Mirrors Warehouse's STDLIB_PROHIBITED (warehouse/packaging/services.py): every
// module from pypi/stdlib-list for every Python version, plus each dotted prefix, PEP 503-normalized.
// Run with `node scripts/generate-pypi-stdlib.mjs` when a new Python version is added to stdlib-list.
import { writeFileSync } from "node:fs";

const REPO = "https://raw.githubusercontent.com/pypi/stdlib-list/main/stdlib_list/lists";
const VERSIONS = [
  "2.6",
  "2.7",
  "3.2",
  "3.3",
  "3.4",
  "3.5",
  "3.6",
  "3.7",
  "3.8",
  "3.9",
  "3.10",
  "3.11",
  "3.12",
  "3.13",
  "3.14",
];
const canonicalize = (s) => s.toLowerCase().replace(/[-_.]+/g, "-");
const trim = (s) => s.replace(/^[-_.]+|[-_.]+$/g, "");

const names = new Set();
for (const version of VERSIONS) {
  const res = await fetch(`${REPO}/${version}.txt`);
  if (!res.ok) throw new Error(`${version}: HTTP ${res.status}`);
  for (const module of (await res.text()).split("\n").filter(Boolean)) {
    const parts = module.trim().split(".");
    for (let i = 1; i <= parts.length; i++)
      names.add(canonicalize(trim(parts.slice(0, i).join("."))));
  }
}
names.delete("");

const sorted = [...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
writeFileSync(
  new URL("../packages/core/src/data/pypi-stdlib.ts", import.meta.url),
  `// Generated by scripts/generate-pypi-stdlib.mjs from pypi/stdlib-list (${VERSIONS[0]}–${VERSIONS.at(-1)}). Do not edit.\n` +
    `export const PYPI_STDLIB: ReadonlySet<string> = new Set(${JSON.stringify(sorted)});\n`,
);
console.log(`${sorted.length} names`);
